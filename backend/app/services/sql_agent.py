from langchain_core.tools import tool 
import sqlite3
from pydantic import BaseModel, Field
from langchain_openai import ChatOpenAI
from langchain_core.messages import AIMessage, HumanMessage, ToolMessage, SystemMessage
from app.core.config import openai_api_key



class SQLAgent():
    '''
    Class for SQL Agent and all its tools
    '''

    def __init__(self, data_dir: str,  model="gpt-4o"):
        self.model=ChatOpenAI(
            model=model,
            openai_api_key=openai_api_key
        )
        self.data_dir=data_dir



    @tool
    def get_tables_schema(self,file_name: str)-> str: 
        """
        input: sqlite file name
        output: all the tables with their schema in that sqlite file
        """
        
        db_file=f"{self.data_dir}/{file_name}"
        con=sqlite3.connect(db_file)
        cur=con.cursor()
        cur.execute("SELECT name, sql FROM sqlite_master WHERE type='table';")
        
        tables = cur.fetchall()
        
        if not tables:
            print("No tables found in this database.")
        res=''
        for table in tables:
            table_name = table[0]
            table_schema = table[1]
            
            res+=f"--- Table: {table_name} ---\n"
            res+=table_schema+'\n'
            res+="-" * (len(table_name) + 14) + "\n"
            res+='\n\n\n'
        con.close()
        return res

    @tool
    def fetch_information(self,query: str, sqlite_file_name: str, table_schema: str)-> str:
        """
        input: query(natural language query along with any extra information to be considered during generation of prompt), 
        sqlite_file_name(sql file of the table),  table_schema(schema of that table)

        output: information retrieved from the table(could be insufficient/absent if the data is not present in the table)
        """
        class sql_query_format(BaseModel):
            sql_query: str=Field(description="The Executable Sql query based on user's natural language question")


        sql_query_prompt=f"""
        You are a high-performance, stateless SQL query generator. 
        ## Generate SQL queries that are robust and inclusive
        ## Make sure that you are following the table schema provided to you when creating your sql query
        ## Always write conditions that match text values in a flexible way — for example, use case-insensitive comparisons, partial matches, 
        or pattern matching instead of exact equality when appropriate.
        ## Only generate a single sql command.
        ## Make sure that your syntax is right, use the correct characters(ex. ',",%,/,@, etc)
        ## Following is the user's natural language question: 
        {query}
        ## Following is the table schema: 
        {table_schema}

        """
        
        model_with_output=self.model.with_structured_output(sql_query_format)

        model_res=model_with_output.invoke(sql_query_prompt)
    
        db_file=f"{self.data_dir}/{sqlite_file_name}"

        con=sqlite3.connect(db_file)
        cur=con.cursor()
        print("SQL query executed: ", model_res.sql_query)
        res = cur.execute(model_res.sql_query)
        res = res.fetchall()
        con.close()

        formatter_agent_prompt=f"""
        You are a formatter agent in an agentic workflow, your job is to format response so that the next agent can comprehend it properly. 
        You are a part of sql query generator workflow.
        According to user's query the sql query agent generated a sql query and executed it.
        You will be given the original user query, table schema, sql_query(generated by agent) and the response received after executing it. 
        Your job is to use all this information to format the response from the executed sql query in markdown.
        Include the executed SQL query as well. 
        Formatting should be done in a way such that next agent can understand the data obtained from the table. 
        Only return the formatted markdown response and nothing else


        ## Inputs
        ### User Query
        {query}
        ### Table Schema
        {table_schema}
        ### SQL query
        {model_res.sql_query}
        ### SQL query result
        {res}
        """
        formatted_response= self.model.invoke(formatter_agent_prompt)
        #print(model_res.sql_query)
        return formatted_response.content

    @tool
    def workflow_over():
        """
        dead state function
        this tool is to be called when the agent has given its final response and wants to quit
        """
        print("appel a day keeps doctor away")
    

    def __call__(self, query:str, databases: dict)-> str:
        """
        Takes in the query and the available databases(.sqlite) in format{"names":[n1,n2,n3], "descriptions": [d1,d2,d3]}
        Returns the information retrieved from those databases
        """

        databases_info=""
        for i in range(len(databases['names'])):
            databases_info+=f"|{databases['names'][i]}| {databases['descriptions'][i]}|\n"
        print(databases_info)
        sql_agent_prompt=f"""
        You are the SQL Agent inside a RAG system. Your job is to retrieve all relevant information
        from the available SQLite databases using ONLY the provided tools. You must maximize recall:
        returning extra information is acceptable, but missing relevant information is not.

        You are not allowed to write SQL yourself. All querying must happen through the tools
        `get_tables_schema` and `fetch_information`. You may call tools as many times as needed,
        in any order, until you are certain that no additional information can be retrieved.

        Below are the available SQLite files and their descriptions:
        | Name | Description |
        | :--- | :--- |
        {databases_info}

        -------------------------------
        ## CORE BEHAVIOR EXPECTATIONS
        -------------------------------

        1. **Use tools iteratively and intelligently.**  
        - Always begin by inspecting schemas (`get_tables_schema`) if unsure where data might be.
        - After each tool result, evaluate whether more information could exist elsewhere.
        - Explore multiple tables if they might contain relevant data.

        2. **Never generate SQL.**  
        `fetch_information` accepts natural-language queries.  
        Your job is to craft the most flexible, interpretive natural-language request possible,
        then refine it based on results. 
        Make sure that your natural language request can be executed through a single sql command.

        3. **Be highly flexible and exploratory.**  
        When results are empty or incomplete, try alternative query formulations:
        - broader phrasing
        - case-insensitive variants
        - partial match queries
        - substring or keyword-only queries
        - synonyms or looser descriptions
        - fuzzier interpretations of entities
        - dropping overly strict filters
        - broadening the scope to related concepts

        4. **Use schemas actively.**  
        After seeing table structures, infer likely column names, relationships,
        join possibilities, or indirect storage patterns.
        If a query fails once, try again using a different angle informed by schema knowledge.

        5. **Try multiple styles of queries for robustness.**  
        For example:
        - exact → case-insensitive
        - detailed → minimal
        - structured → keyword-only
        - specific → broad
        - single-table → multi-table exploration

        6. **Never stop after first successful result.**  
        Continue until you are highly confident that no further exploration will yield new information.

        7. **Output format**  
        For every step include a brief structured block like:
        planning:
        What you understood from results
        Whether more information could exist
        What tool call will be used next and why

        Only at the very end output:
        Your final response
        <After final respone call the workflow over tool>

        8. **Termination condition**  
        Stop only when:
        - Every relevant table has been explored sufficiently, AND  
        - Multiple query styles have been attempted, AND  
        - You reasonably conclude no more information can be retrieved.
        - There are no sqlite files given to you

        -------------------------------
        ## GOAL
        -------------------------------
        Your goal is to gather **all** potentially relevant information from the available databases,
        using iterative tool calls and flexible query strategies, until confident that exploration
        is complete. Then provide a single concise final_answer.

        Always prioritize completeness over precision.

        """


        sys_message=SystemMessage(content=sql_agent_prompt)
        hum_message=HumanMessage(content=query)

        tools = [self.get_tables_schema, self.fetch_information, self.workflow_over]

        llm = ChatOpenAI(model="gpt-4o", temperature=1)
        model_with_tools = llm.bind_tools(tools)

        history = [sys_message, hum_message]

        response=""
        while True:
            
            ai_response = model_with_tools.invoke(history)
            history.append(ai_response) 
            
            
            flag=False
            if ai_response.tool_calls:
                tool_messages_to_add = []
                
                for tool_call in ai_response.tool_calls:
                    #print("Tool Called with id: ", tool_call['id'],tool_call['name'],tool_call['args'], "-"*100)
                    if tool_call['name'] == 'get_tables_schema':

                        tool_result=self.get_tables_schema.func(self,tool_call['args']['file_name'])
                        
                        #print(tool_result,'\n\n\n')
                    elif tool_call['name'] == 'fetch_information':

                        tool_result = self.fetch_information.func(self,
                            tool_call['args']['query'],
                            tool_call['args']['sqlite_file_name'],
                            tool_call['args']['table_schema']
                        )
                        #print(f"Called with: {tool_call['args']['query']}")
                        #print(tool_result, '\n\n\n')
                    elif tool_call['name']=='workflow_over':
                       # response=self.workflow_over.func(tool_call['args']['final_res'])
                        flag=True

                        break 
                    else:
                        tool_result = f"Error: Unknown tool {tool_call['name']}"
                    
                    tool_messages_to_add.append(
                        ToolMessage(content=str(tool_result), tool_call_id=tool_call['id'])
                    )
                
                history.extend(tool_messages_to_add)
            else:
               # print('AI Message', '*'*50)
                #print(ai_response.content, '\n\n\n')
                ai_message=AIMessage(content=ai_response.content)
                response=ai_response.content
                history.append(ai_message)
                break  # Exit loop when model gives final response without tool calls
            if(flag):
                break

        #print("\n\nFinal Response: \n\n", response)
        return response

